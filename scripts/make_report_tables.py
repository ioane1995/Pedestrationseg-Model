"""Collect results/*/metrics.json (+ optimisation/error-analysis of the best run) into results/RESULTS.md and CSV.
    python scripts/make_report_tables.py              # write tables
    python scripts/make_report_tables.py --print-best # print name of best experiment (by VAL segm mAP)
"""
import argparse
import csv
import json
from pathlib import Path


def load_all(results):
    runs = []
    for p in sorted(Path(results).glob("*/metrics.json")):
        runs.append(json.load(open(p)))
    return runs


def f(x, n=3):
    return "-" if x is None else f"{x:.{n}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--print-best", action="store_true")
    a = ap.parse_args()
    runs = load_all(a.results)
    if not runs:
        raise SystemExit("no results found - run scripts/run_experiments.sh first")
    best = max(runs, key=lambda r: r["val"]["segm_map"])
    if a.print_best:
        print(best["name"])
        return

    L = ["# Results (auto-generated by scripts/make_report_tables.py)\n",
         "All runs: identical fixed split (train 120 / val 20 / test 30), same epochs & seed. "
         "Best run is selected on **validation** segm mAP; test numbers are reported once.\n",
         "## 1. Experiments\n",
         "| Experiment | Model | Pretrained | Train. layers | Aug | Optim | LR | Best ep | Val segm mAP | Test segm mAP | Test segm mAP50 | Test bbox mAP | Trainable params (M) | Train time (min) |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    rows = []
    for r in runs:
        g = r["args"]
        star = " **(best)**" if r["name"] == best["name"] else ""
        L.append(f"| {r['name']}{star} | {g['model']} | {'no' if g['no_pretrained'] else 'COCO'} | {g['trainable_layers']} | {g['aug']} | "
                 f"{g['optim']} | {g['lr']} | {r['best_epoch']} | {f(r['val']['segm_map'])} | {f(r['test']['segm_map'])} | "
                 f"{f(r['test']['segm_map_50'])} | {f(r['test']['bbox_map'])} | {r['params_trainable']/1e6:.1f} | {r['train_time_s']/60:.1f} |")
        rows.append({"name": r["name"], **{k: g[k] for k in ("model", "no_pretrained", "trainable_layers", "aug", "optim", "lr")},
                     "best_epoch": r["best_epoch"], "val_segm_map": r["val"]["segm_map"], "test_segm_map": r["test"]["segm_map"],
                     "test_segm_map50": r["test"]["segm_map_50"], "test_bbox_map": r["test"]["bbox_map"]})
    with open(Path(a.results) / "experiments.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)

    bd = Path(a.results) / best["name"]
    opt = bd / "optimization.json"
    if opt.exists():
        o = json.load(open(opt))
        L += [f"\n## 2. Optimisation of `{best['name']}` (test set, batch size 1, {o['n_latency_images']} images)\n",
              "| Variant | Device | Short side | Size (MB) | Latency mean (ms) | p95 (ms) | FPS | Segm mAP | Segm mAP50 | Note |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for r in o["rows"]:
            if "latency_ms_mean" not in r:
                L.append(f"| {r['variant']} | {r.get('device','-')} | - | - | - | - | - | - | - | {r.get('note','')} |")
                continue
            L.append(f"| {r['variant']} | {r['device']} | {r['min_size']} | {r['size_mb']:.1f} | {r['latency_ms_mean']:.1f} | "
                     f"{r['latency_ms_p95']:.1f} | {r['fps']:.1f} | {r['segm_map']:.3f} | {r['segm_map50']:.3f} | {r['note']} |")
    ea = bd / "error_analysis.json"
    if ea.exists():
        e = json.load(open(ea))
        L += [f"\n## 3. Error analysis of `{best['name']}` (test set, score >= {e['operating_threshold']})\n",
              f"Precision {e['precision']:.3f} | Recall {e['recall']:.3f} | F1 {e['f1']:.3f} | mean mask IoU of matched instances {e['mean_tp_mask_iou']:.3f} "
              f"(TP={e['tp']}, FP={e['fp']}, FN={e['fn']})\n",
              f"False positives by type: {e['false_positive_types']}\n",
              f"Recall by pedestrian size: {({k: round(v, 3) for k, v in e['recall_by_size'].items()})}",
              f"\nRecall by crowdedness: {({k: round(v, 3) for k, v in e['recall_by_crowdedness'].items()})}\n",
              "| Score threshold | Precision | Recall | F1 |", "|---|---|---|---|"]
        for t, v in e["threshold_sweep"].items():
            L.append(f"| {t} | {v['precision']:.3f} | {v['recall']:.3f} | {v['f1']:.3f} |")
        L.append(f"\nWorst-image visualisations: `results/{best['name']}/error_analysis/`")
    (Path(a.results) / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("wrote", Path(a.results) / "RESULTS.md", "| best:", best["name"])


if __name__ == "__main__":
    main()
