"""Penn-Fudan Pedestrian dataset: download, fixed splits, torch Dataset, augmentations.

Splits are FIXED (seed=42) and independent of the training seed, so every experiment is
evaluated on exactly the same validation / test images (fair comparison, no test leakage:
model selection uses *val* only, *test* is reported once at the end).
"""
import random
import urllib.request
import zipfile
from pathlib import Path

import numpy as np
import torch
from PIL import Image
from torchvision import tv_tensors
from torchvision.ops import masks_to_boxes
from torchvision.transforms import v2 as T
from torchvision.transforms.v2 import functional as F

URL = "https://www.cis.upenn.edu/~jshi/ped_html/PennFudanPed.zip"


def download_dataset(root="data") -> Path:
    root = Path(root)
    target = root / "PennFudanPed"
    if target.exists():
        return target
    root.mkdir(parents=True, exist_ok=True)
    zpath = root / "PennFudanPed.zip"
    print(f"Downloading Penn-Fudan dataset to {zpath} ...")
    urllib.request.urlretrieve(URL, zpath)
    with zipfile.ZipFile(zpath) as z:
        z.extractall(root)
    return target


def make_splits(n, seed=42, n_val=20, n_test=30):
    """Deterministic train/val/test split of n items -> (train, val, test) index lists."""
    idx = list(range(n))
    random.Random(seed).shuffle(idx)
    test = sorted(idx[:n_test])
    val = sorted(idx[n_test:n_test + n_val])
    train = sorted(idx[n_test + n_val:])
    return train, val, test


def build_transforms(train: bool, aug: str):
    """aug: none | basic (flip + colour jitter) | strong (photometric + zoom-out + IoU-crop + flip)."""
    t = []
    if train and aug == "basic":
        t += [T.RandomHorizontalFlip(0.5), T.ColorJitter(0.3, 0.3, 0.3, 0.02)]
    elif train and aug == "strong":
        t += [T.RandomPhotometricDistort(), T.RandomZoomOut(side_range=(1.0, 1.8)),
              T.RandomIoUCrop(), T.RandomHorizontalFlip(0.5)]
    t += [T.ToDtype(torch.float, scale=True)]
    if train and aug == "strong":
        t += [T.SanitizeBoundingBoxes()]  # drop boxes/masks degenerated by cropping
    t += [T.ToPureTensor()]
    return T.Compose(t)


class PennFudanDataset(torch.utils.data.Dataset):
    """Instance segmentation: every pedestrian = one instance, label 1 (0 = background)."""

    def __init__(self, root, indices=None, train=False, aug="none"):
        self.root = Path(root)
        self.imgs = sorted(p.name for p in (self.root / "PNGImages").glob("*.png"))
        self.masks = sorted(p.name for p in (self.root / "PedMasks").glob("*.png"))
        assert len(self.imgs) == len(self.masks) > 0, "dataset not found / corrupted"
        self.indices = list(range(len(self.imgs))) if indices is None else list(indices)
        self.transforms = build_transforms(train, aug)

    def __len__(self):
        return len(self.indices)

    def __getitem__(self, i):
        k = self.indices[i]
        img = Image.open(self.root / "PNGImages" / self.imgs[k]).convert("RGB")
        mask = np.array(Image.open(self.root / "PedMasks" / self.masks[k]))
        ids = np.unique(mask)
        ids = ids[ids != 0]  # 0 = background
        masks = torch.from_numpy(mask == ids[:, None, None]).to(torch.uint8)  # [N,H,W]
        boxes = masks_to_boxes(masks)
        labels = torch.ones(len(ids), dtype=torch.int64)
        img = tv_tensors.Image(img)
        target = {
            "boxes": tv_tensors.BoundingBoxes(boxes, format="XYXY", canvas_size=F.get_size(img)),
            "masks": tv_tensors.Mask(masks),
            "labels": labels,
            "image_id": k,
            "area": (boxes[:, 3] - boxes[:, 1]) * (boxes[:, 2] - boxes[:, 0]),
            "iscrowd": torch.zeros(len(ids), dtype=torch.int64),
        }
        img, target = self.transforms(img, target)
        return img, target


def collate_fn(batch):
    return tuple(zip(*batch))


def get_datasets(root, aug="none"):
    root = Path(root)
    n = len(list((root / "PNGImages").glob("*.png")))
    tr, va, te = make_splits(n)
    return (PennFudanDataset(root, tr, train=True, aug=aug),
            PennFudanDataset(root, va, train=False),
            PennFudanDataset(root, te, train=False))
